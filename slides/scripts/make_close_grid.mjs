// One-off generator for the grid structure behind the closing slide.
//
// The corporate master's `Schlussfolie` carries a full-slide wireframe of thin
// light-blue triangles ("Gitterstruktur", a 961-point freeform in the .potx).
// That shape belongs to the template, which is gitignored and not ours to
// publish -- so this draws an equivalent mesh from the master's palette colour
// `acc4` #8BD3E6 instead of extracting theirs.
//
// Deterministic: the jitter comes from a seeded PRNG, so re-running writes a
// byte-identical file. Output is committed, like the QR code, and the build
// never generates it.
//
// Usage: node scripts/make_close_grid.mjs [seed] [outfile]
//   node scripts/make_close_grid.mjs 20260914 public/close-grid.svg

import { writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const seed = Number(process.argv[2] ?? 20260914)
const out = resolve(root, process.argv[3] ?? 'public/close-grid.svg')

// mulberry32 -- small, specified, and identical on every platform.
function rng(a) {
  return function () {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const W = 980 // Slidev's canvas, so the mesh is authored at the size it renders
const H = 552
const COLS = 16
const ROWS = 9
const CELL_W = W / COLS
const CELL_H = H / ROWS

const rand = rng(seed)
const pt = []
for (let r = 0; r <= ROWS; r++) {
  pt[r] = []
  for (let c = 0; c <= COLS; c++) {
    // Jitter every interior vertex; keep the outer ring on the slide edge so the
    // mesh bleeds off rather than stopping in a visible rectangle.
    const jx = c === 0 || c === COLS ? 0 : (rand() - 0.5) * CELL_W * 0.55
    const jy = r === 0 || r === ROWS ? 0 : (rand() - 0.5) * CELL_H * 0.55
    pt[r][c] = [round(c * CELL_W + jx), round(r * CELL_H + jy)]
  }
}

function round(v) {
  return Math.round(v * 10) / 10
}

// Opacity rises towards the right edge: the address block sits on the left and
// has to stay readable, and the master's grid is densest away from the text.
function opacity(x) {
  const t = Math.min(1, Math.max(0, x / W))
  return round2(0.12 + 0.5 * t * t)
}
function round2(v) {
  return Math.round(v * 100) / 100
}

const lines = []
for (let r = 0; r < ROWS; r++) {
  for (let c = 0; c < COLS; c++) {
    const a = pt[r][c]
    const b = pt[r][c + 1]
    const d = pt[r + 1][c]
    const e = pt[r + 1][c + 1]
    // Two triangles per cell, alternating the diagonal so the mesh does not
    // read as a regular grid.
    const diag = (r + c) % 2 === 0 ? [a, e] : [b, d]
    for (const [p, q] of [[a, b], [a, d], diag]) {
      const o = opacity((p[0] + q[0]) / 2)
      lines.push(
        `  <line x1="${p[0]}" y1="${p[1]}" x2="${q[0]}" y2="${q[1]}" opacity="${o}"/>`,
      )
    }
  }
}
// The right and bottom edges of the last row/column.
for (let r = 0; r < ROWS; r++) {
  const p = pt[r][COLS]
  const q = pt[r + 1][COLS]
  lines.push(`  <line x1="${p[0]}" y1="${p[1]}" x2="${q[0]}" y2="${q[1]}" opacity="${opacity(W)}"/>`)
}
for (let c = 0; c < COLS; c++) {
  const p = pt[ROWS][c]
  const q = pt[ROWS][c + 1]
  lines.push(
    `  <line x1="${p[0]}" y1="${p[1]}" x2="${q[0]}" y2="${q[1]}" opacity="${opacity((p[0] + q[0]) / 2)}"/>`,
  )
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="presentation">
<!-- Generated by scripts/make_close_grid.mjs, seed ${seed}. Imitates the grid
     structure of the corporate master's closing slide in its own palette colour
     acc4 #8BD3E6; the template's shape itself is not used. -->
<g stroke="#8BD3E6" stroke-width="0.7" fill="none" stroke-linecap="round">
${lines.join('\n')}
</g>
</svg>
`
writeFileSync(out, svg, { encoding: 'utf8' })
console.log(`make_close_grid: seed ${seed} -> ${out} (${svg.length} bytes, ${lines.length} lines)`)
